L=json.load(open('layouts_raw.json'))
def tpoly(t):
    w,h=NOM[t['type']]; w/=2; h/=2
    pts=[[-w,h-2],[w,-h],[w,h],[-w,h]] if t['type']=='tri' else [[-w,-h],[w,-h],[w,h],[-w,h]]
    a=math.radians(t['rot']); c,s=math.cos(a),math.sin(a); out=[]
    for x,y in pts:
        if t['mirror']: x=-x
        out.append((x*c-y*s+t['x'], x*s+y*c+t['y']))
    return out
def pip(p,poly):
    x,y=p; ins=False; n=len(poly)
    for i in range(n):
        x1,y1=poly[i]; x2,y2=poly[(i+1)%n]
        if (y1>y)!=(y2>y) and x < (x2-x1)*(y-y1)/(y2-y1)+x1: ins=not ins
    return ins
def segd(p,a,b):
    dx,dy=b[0]-a[0],b[1]-a[1]; l2=dx*dx+dy*dy
    t=max(0,min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/l2)) if l2 else 0
    return math.hypot(p[0]-a[0]-t*dx,p[1]-a[1]-t*dy)
def pdist(p,poly):
    if pip(p,poly): return 0
    return min(segd(p,poly[i],poly[(i+1)%len(poly)]) for i in range(len(poly)))
ABBR={'TAKE AND HOLD':'TH','PURGE THE FOE':'PF','PRIORITY ASSETS':'PA','RECONNAISSANCE':'RE','DISRUPTION':'DI'}
def tc(s): 
    s=s.title().replace('’S','’s').replace("'S","'s")
    return re.sub(r'\bAnd\b','and',re.sub(r'\bThe\b','the',s)).replace('the Foe','the Foe')
def clean_zone(pts):
    out=[]
    for x,y in pts:
        if x<0.4: x=0.0
        if x>43.6: x=44.0
        if y<0.4: y=0.0
        if y>59.6: y=60.0
        if out and abs(out[-1][0]-x)<0.06 and abs(out[-1][1]-y)<0.06: continue
        out.append([round(x,2),round(y,2)])
    if len(out)>2 and abs(out[0][0]-out[-1][0])<0.06 and abs(out[0][1]-out[-1][1])<0.06: out.pop()
    return out
res=[]
for l in L:
    tl,tr=l['titles']['L'],l['titles']['R']
    def grab(t):
        i=t.index('MISSION') if 'MISSION' in t else None
        disp=t[1] if len(t)>1 else '?'; mis=t[i+1] if i is not None and i+1<len(t) else '?'
        return disp,mis
    d1,m1=grab(tl); d2,m2=grab(tr)
    terr=[]; polys=[]
    for t in l['terrain']:
        terr.append(dict(type=t['type'],x=round(t['x'],3),y=round(t['y'],3),rot=round(t['rot'],2),mirror=bool(t['mirror'])))
        polys.append(tpoly(t))
    # groups via single-area icons
    parent=list(range(len(terr)))
    def find(i):
        while parent[i]!=i: parent[i]=parent[parent[i]]; i=parent[i]
        return i
    for k in l['links']:
        if not k['single']: continue
        ds=sorted(((pdist((k['x'],k['y']),p),i) for i,p in enumerate(polys)))
        a,b=ds[0][1],ds[1][1]
        if ds[1][0]<2.0: parent[find(a)]=find(b)
    groups={}
    for i in range(len(terr)): groups.setdefault(find(i),[]).append(i)
    gid={r:n+1 for n,r in enumerate(sorted(groups))}
    for i,t in enumerate(terr): t['area']=gid[find(i)]
    # features
    feats=[]
    dense=set(); anyf=set()
    for f in l['features']:
        pts=f['points']; c=(sum(p[0] for p in pts)/4,sum(p[1] for p in pts)/4)
        hit=None
        for i,p in enumerate(polys):
            if pip(c,p): hit=i; break
        if hit is None:
            ds=min((pdist(c,p),i) for i,p in enumerate(polys)); hit=ds[1] if ds[0]<1.5 else None
        if hit is not None:
            anyf.add(terr[hit]['area'])
            if f['kind']=='dense': dense.add(terr[hit]['area'])
        feats.append(dict(kind=f['kind'],points=[[round(a,2),round(b,2)] for a,b in pts]))
    for t in terr:
        t['dense']=t['area'] in dense
        t['obscuring']=t['area'] in anyf
    objs=[]
    for o in l['objectives']:
        hit=None
        for i,p in enumerate(polys):
            if pip((o['x'],o['y']),p): hit=i; break
        kind={'homeA':'home-attacker','homeB':'home-defender'}.get(o['kind'],o['kind'])
        objs.append(dict(kind=kind,x=o['x'],y=o['y'],area=terr[hit]['area'] if hit is not None else None))
    zid='%s-%s-%s'%(ABBR.get(d1,'XX'),ABBR.get(d2,'XX'),l['letter'])
    res.append(dict(id=zid.lower(),name='%s vs %s — Layout %s'%(tc(d1),tc(d2),l['letter']),
        dispositions=[tc(d1),tc(d2)], missions=[tc(m1),tc(m2)], letter=l['letter'], page=l['page'],
        board=dict(w=44,h=60), terrain=terr, zones=[dict(player=z['player'],points=clean_zone(z['points'])) for z in l['zones']],
        objectives=objs))
    if len([o for o in objs if o['area'] is None]): print('objective not on terrain', zid, [o for o in objs if o['area'] is None])
